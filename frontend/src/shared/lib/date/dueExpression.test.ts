import { formatMonthDayWeekday, resolveDueExpression } from './dueExpression'

/*
 * 기대 날짜는 달력에서 손으로 셌다. 기준: 2026-09-18 은 금요일이라 2026-09-14(월)~09-20(일)이 한 주다.
 * 2026-12-25 는 그로부터 14주 뒤라 금요일, 2026-12-28 월요일, 2027-01-01·01-08 금요일이다. 2028 은 윤년이다
 */

describe('마감 표현 읽기', () => {
  it.each([
    // 모의 데이터의 회의 mt_09 는 2026-09-15(화, 서울) 회의다
    ['다음 주 월요일', '2026-09-15', '2026-09-21'],
    ['26일', '2026-09-15', '2026-09-26'],
    ['오늘', '2026-09-15', '2026-09-15'],
    ['내일', '2026-09-15', '2026-09-16'],
    ['모레', '2026-09-15', '2026-09-17'],
    ['내일', '2026-12-31', '2027-01-01'],
    ['이번 주 금요일', '2026-09-16', '2026-09-18'],
    ['이번 주 수요일', '2026-09-16', '2026-09-16'],
    ['이번 주 일요일', '2026-09-16', '2026-09-20'],
    ['다음 주 월요일', '2026-09-20', '2026-09-21'],
    ['다음 주 일요일', '2026-09-14', '2026-09-27'],
    ['다음 주 금요일', '2026-12-30', '2027-01-08'],
    ['3일 뒤', '2026-09-15', '2026-09-18'],
    ['10일 후', '2026-09-25', '2026-10-05'],
    ['365일 뒤', '2026-01-01', '2027-01-01'],
    ['9월 21일', '2026-09-15', '2026-09-21'],
    ['9월 15일', '2026-09-15', '2026-09-15'],
    ['1월 5일', '2026-12-28', '2027-01-05'],
    ['2월 29일', '2028-01-10', '2028-02-29'],
    ['3월 31일', '2026-12-30', '2027-03-31'],
    ['3일', '2026-01-30', '2026-02-03'],
    ['5일', '2026-12-20', '2027-01-05'],
    ['31일', '2026-01-31', '2026-01-31'],
    ['29일', '2028-02-10', '2028-02-29'],
  ])('%s (기준 %s) → %s', (raw, base, expected) => {
    expect(resolveDueExpression(raw, base)).toBe(expected)
  })

  it.each([
    ['다음주 월요일'],
    ['다음 주월요일'],
    ['  다음 주 월요일  '],
    ['다음 주 월요일까지'],
    ['다음 주 월요일까지는'],
    ['다음 주 월요일에'],
    ['다음 주 월요일에는'],
  ])('띄어쓰기와 뜻을 바꾸지 않는 조사는 무시한다: "%s"', (raw) => {
    expect(resolveDueExpression(raw, '2026-09-15')).toBe('2026-09-21')
  })

  it.each([
    // 회의 mt_08 의 승인 ap_07. 날짜가 아니다
    ['배포 전', '2026-09-11'],
    ['이번 주 월요일', '2026-09-16'],
    ['31일', '2026-02-10'],
    ['30일', '2026-01-31'],
    ['29일', '2027-02-10'],
    ['2월 29일', '2027-01-10'],
    ['2월 29일', '2027-03-01'],
    ['9월 1일', '2026-09-15'],
    ['8월 31일', '2026-09-15'],
    ['4월 2일', '2026-12-30'],
    ['2월 30일', '2026-01-10'],
    ['13월 1일', '2026-09-15'],
    ['0월 1일', '2026-09-15'],
    ['0일', '2026-09-15'],
    ['32일', '2026-09-15'],
    ['0일 뒤', '2026-09-15'],
    ['366일 뒤', '2026-01-01'],
  ])('달력에 없거나 기준일보다 앞인 날은 읽지 않는다: "%s" (기준 %s)', (raw, base) => {
    expect(resolveDueExpression(raw, base)).toBeNull()
  })

  it.each([
    ['내일 전'],
    ['다음 주 월요일 전'],
    ['모레쯤'],
    ['이번 주 중'],
    ['3일 이내'],
    ['내일 안에'],
    ['내일 오후'],
    ['내일까지까지'],
    ['월요일'],
    ['목요일까지'],
    ['다음 주'],
    ['다음 달'],
    ['주말'],
    ['글피'],
    ['사흘 뒤'],
    ['삼 일 뒤'],
    ['2주 뒤'],
    ['9/21'],
    ['다음 주 월'],
    [''],
    ['   '],
  ])('하나로 정해지지 않거나 모르는 표현은 읽지 않는다: "%s"', (raw) => {
    expect(resolveDueExpression(raw, '2026-09-15')).toBeNull()
  })

  describe('실행 환경 시간대와 무관하다', () => {
    const original = process.env.TZ
    afterEach(() => {
      if (original === undefined) delete process.env.TZ
      else process.env.TZ = original
    })

    it.each(['Pacific/Honolulu', 'Pacific/Kiritimati', 'Asia/Seoul'])('%s', (timeZone) => {
      process.env.TZ = timeZone
      expect(resolveDueExpression('다음 주 금요일', '2026-12-30')).toBe('2027-01-08')
      expect(formatMonthDayWeekday('2026-09-21')).toBe('9/21(월)')
    })
  })
})

describe('월/일(요일) 표기', () => {
  it.each([
    ['2026-09-21', '9/21(월)'],
    ['2026-12-05', '12/5(토)'],
    ['2027-01-03', '1/3(일)'],
    ['2028-02-29', '2/29(화)'],
  ])('%s → %s', (date, expected) => {
    expect(formatMonthDayWeekday(date)).toBe(expected)
  })
})
