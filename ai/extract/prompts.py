"""LLM 프롬프트 한 곳 모음. 판단 기준 자체는 extract/TASK_CRITERIA.md 가 원본이다.

few-shot 예시는 **골든셋(extract/golden_set/)과 절대 겹치지 않게** 새로 지은 문장만 쓴다 —
채점용 문장을 프롬프트에 넣으면 시험 문제를 미리 보여주고 시험 치는 꼴이라 점수가 부풀려진다.
"""

from __future__ import annotations

from datetime import date

ASSIGNEE_TYPES = ("first", "second", "thirdname", "thirdpronoun", "thirdrole", "all", "none")

# ─────────────────────────────────────────────────────────── 1단계: 관련성 필터
RELEVANCE_SYSTEM = """너는 팀 회의 대화록에서 '할일'이 담긴 문장만 골라내는 필터다.

할일로 인정하려면 셋 다 만족해야 한다:
1. 구체적인 행동이나 산출물이 있다 (누가 무엇을 한다)
2. 아직 안 끝났다 (이미 끝난 일의 보고는 제외)
3. 하겠다는 의지나 해달라는 요청이 있다 (단순 가능성·희망·추측은 제외)

애매한 경우의 판단:
- 조건부("시간 되면 해볼게요")는 할일로 **포함**한다
- 사고 활동만("고민해볼게요")은 **제외**, 산출물이 붙으면("고민해보고 공유드릴게요") **포함**
- 질문형("이거 누가 하죠?")은 아직 결정된 게 없으므로 **제외**
- 제3자 추측("환이가 할 것 같은데요")은 결정이 아니므로 **제외**
- 미완료 보고("아직 못 했어요")는 **제외**, 다만 뒤에 새 약속이 붙으면 그 문장은 포함
- 이미 하던 일을 계속하겠다는 선언("계속 진행하겠습니다")은 **마감이 같이 나오면 포함**,
  마감 없이 계속하겠다고만 하면 상태 보고에 가까우므로 **제외**
- 보류("다음에 얘기하죠"), 회의 진행 발언("시작할게요", "여기까지 하죠", "각자 공유해주세요",
  "편하게 말씀해주세요")은 **제외** — 회의를 굴리기 위한 말이지 추적할 할일이 아니다
- "다 같이 검토하죠"처럼 담당자가 특정 안 되는 것도 할일이므로 **포함**

예시:
[포함] "이 PR 오늘 중으로 올릴게요"            구체적 산출물 + 의지
[포함] "환 님이 배포 스크립트 좀 봐주세요"        타인에게 요청
[포함] "여유 되면 문서도 정리해둘게요"           조건부지만 행동은 분명
[제외] "어제 서버 세팅하다가 밤새웠어요"          이미 끝난 일의 근황
[제외] "그건 좀 고민해볼게요"                  산출물 없는 사고 활동
[제외] "이 부분은 누가 맡죠?"                  아직 결정 안 됨
[제외] "점심 뭐 드실 거예요?"                  잡담

한 발화에 잡담과 할일이 섞여 있으면 할일에 해당하는 문장 번호만 고른다."""


def relevance_user_prompt(numbered_lines: str) -> str:
    return f"대화록:\n{numbered_lines}\n\n할일이 담긴 문장의 번호만 relevant_indices 로 반환해라."


# ─────────────────────────────────────────────────────── 2단계: 구조화 추출
def extraction_system_prompt(today: date) -> str:
    """기준일을 반드시 프롬프트에 박는다 — 이게 빠지면 상대 날짜가 전부 조용히 틀린다."""
    weekday = "월화수목금토일"[today.weekday()]
    return f"""너는 팀 회의 대화록에서 할일의 세부 정보를 뽑는 추출기다.
오늘은 {today.isoformat()} ({weekday}요일)이다.

각 문장마다 아래 순서대로 채워라 (근거를 먼저 정리하고 결론을 내라. 결론부터 정하고 끼워맞추지 마라):

1. evidence_span — 할일·담당자·마감의 근거가 되는 부분을 원문 그대로 인용
2. reasoning — 왜 이 담당자/마감으로 판단했는지 근거를 먼저 서술
3. task_raw — 할일 내용을 간결하게 (원문 표현을 살리되 군더더기는 뺀다)
4. assignee_type — 담당자를 어떻게 지칭했는지 분류:
   - first: 화자 자신 ("제가", "저는", "내가"). **이름을 채우지 말고 타입만 표시**한다
   - second: 상대방 지칭 ("너가", "당신이")
   - thirdname: 제3자를 이름·별명으로 ("환 님이", "하은이가")
   - thirdpronoun: 제3자를 지시대명사로 ("그분이", "저쪽에서")
   - thirdrole: 역할·직책으로 ("백엔드 리더가", "디자인 담당이")
   - all: 참석자 전원이 담당. 전원을 가리키는 표현이 원문에 있을 때만 쓴다
     ("다 같이", "우리 모두", "전체가", "각자"). 그런 표현 없이 담당자를 안 밝힌
     청유형이면 all 이 아니라 none 이다
   - none: 담당자 언급이 전혀 없음
5. assignee_mention — 담당자를 가리킨 표현을 **원문 그대로**. first/all/none 이면 null
6. assignee_resolved — second/thirdpronoun 처럼 그 표현만으로는 누군지 모르는 경우,
   **앞뒤 문맥을 보고** 실제 사람 이름으로 바꿔라 (예: "그분" → "환"). 문맥으로도 모르면 null.
   다른 타입이면 null
7. due_date — 마감일을 실제 날짜(YYYY-MM-DD)로 계산해서 넣어라. 오늘 날짜는 위에 있다.
   - "월요일까지"처럼 요일만 있으면 오늘 기준 가장 가까운 다음 해당 요일로 본다
   - 요일이 특정되지 않은 기간 표현은 **그 기간의 마지막 날**로 확정한다:
     "이번 주 안으로" → 이번 주 일요일, "다음 주까지" → 다음 주 일요일, "월말까지" → 그 달 마지막 날
   - 마감 표현이 없으면 null. 날짜를 지어내지 마라
8. due_raw — 마감을 가리킨 표현 원문 그대로 ("이번 주 목요일까지"). 없으면 null
9. ambiguity_flag — 담당자나 마감이 불명확해서 추측이 필요했으면 true"""


def extraction_user_prompt(numbered_lines: str) -> str:
    return f"대상 문장:\n{numbered_lines}"
